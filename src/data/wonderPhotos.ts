export function photosFor(siteId: string): WonderPhoto[] {
  return WONDER_PHOTOS[siteId] ?? [];
}

/** First 'wide' or 'facade' photo, used as the hero image. */
export function heroPhoto(siteId: string): WonderPhoto | undefined {
  const photos = photosFor(siteId);
  return photos.find(p => p.kind === 'wide' || p.kind === 'facade') ?? photos[0];
}
